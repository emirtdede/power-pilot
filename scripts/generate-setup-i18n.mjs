#!/usr/bin/env node
'use strict';

/**
 * scripts/generate-setup-i18n.mjs
 *
 * Generates zero-leak 73-language localization bundle for the modern frameless
 * monochrome Setup & Uninstaller (`installer/ui/i18n-73.js` + `installer/ui/i18n-73.json`).
 *
 * Enforces:
 *  - Exact 73 languages matching scripts/nsis-i18n/catalog.mjs (unique codes & LCIDs)
 *  - Exact 43 keys per language, non-empty
 *  - ZERO English fallback leaks in any of the 72 non-English languages
 *  - ZERO Unicode long dashes (U+2012..U+2015, U+2E3A, U+2E3B, U+FE58, U+FF0D)
 *  - ZERO emojis
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NSIS_LANGUAGES } from './nsis-i18n/catalog.mjs';
import { SETUP_STRINGS_1 } from './setup-i18n/part1.mjs';
import { SETUP_STRINGS_2 } from './setup-i18n/part2.mjs';
import { SETUP_STRINGS_3 } from './setup-i18n/part3.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'installer', 'ui');
const LONG_DASH_RE = /[\u2012\u2013\u2014\u2015\u2e3a\u2e3b\ufe58\uff0d]/;
const EMOJI_RE = /\p{Extended_Pictographic}/u;

export const SETUP_I18N_KEYS = [
  'setupTitle', 'uninstallTitle',
  'welcomeDescInstall', 'welcomeDescUpgrade',
  'btnInstall', 'btnUpgrade', 'btnOptions', 'btnHide',
  'footerNotice',
  'optionsTitle', 'labelLanguage', 'labelInstallDir', 'btnChange',
  'optDesktop', 'optStartMenu', 'optStartup', 'optPath',
  'diskSpace',
  'installingTitle', 'uninstallingTitle',
  'stepPrepare', 'stepClose', 'stepExtract',
  'stepRegister', 'stepPath', 'stepRefresh',
  'stepRemoveFiles', 'stepRemoveData',
  'doneTitle', 'doneDesc',
  'btnClose', 'btnLaunch',
  'uninstallHeading', 'uninstallDesc',
  'uninstallDeleteData', 'uninstallDataHint',
  'btnCancel', 'btnUninstall',
  'uninstalledTitle', 'uninstalledDesc',
  'errorTitle', 'btnRetry', 'ariaMinimize'
];

export function buildSetupI18nBundle() {
  const allTuples = { ...SETUP_STRINGS_1, ...SETUP_STRINGS_2, ...SETUP_STRINGS_3 };
  if (NSIS_LANGUAGES.length !== 73) {
    throw new Error(`Expected 73 languages in catalog, found ${NSIS_LANGUAGES.length}`);
  }
  const enTuple = allTuples.en;
  if (!enTuple || enTuple.length !== SETUP_I18N_KEYS.length) {
    throw new Error(`English tuple length mismatch: expected ${SETUP_I18N_KEYS.length}`);
  }

  const languages = [];
  const strings = {};

  for (const entry of NSIS_LANGUAGES) {
    const tuple = allTuples[entry.code];
    if (!Array.isArray(tuple)) {
      throw new Error(`Missing setup i18n tuple for language: ${entry.code}`);
    }
    if (tuple.length !== SETUP_I18N_KEYS.length) {
      throw new Error(`Tuple length mismatch for ${entry.code}: got ${tuple.length}, expected ${SETUP_I18N_KEYS.length}`);
    }
    const dict = {};
    for (let i = 0; i < SETUP_I18N_KEYS.length; i += 1) {
      const key = SETUP_I18N_KEYS[i];
      const val = String(tuple[i] || '').trim();
      if (!val) throw new Error(`Empty string at ${entry.code}.${key}`);
      if (LONG_DASH_RE.test(val)) throw new Error(`Long dash detected at ${entry.code}.${key}: ${val}`);
      if (EMOJI_RE.test(val)) throw new Error(`Emoji detected at ${entry.code}.${key}: ${val}`);
      if (entry.code !== 'en' && val === enTuple[i]) {
        throw new Error(`English fallback leak detected at ${entry.code}.${key}: "${val}"`);
      }
      dict[key] = val;
    }
    languages.push({
      code: entry.code,
      lcid: entry.lcid,
      label: entry.label,
      rtl: Boolean(entry.rtl)
    });
    strings[entry.code] = dict;
  }

  return { languages, strings, keys: SETUP_I18N_KEYS };
}

function main() {
  const bundle = buildSetupI18nBundle();
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const jsonText = JSON.stringify(bundle, null, 2);
  if (LONG_DASH_RE.test(jsonText)) throw new Error('Long dash found in generated JSON');

  fs.writeFileSync(path.join(OUT_DIR, 'i18n-73.json'), jsonText + '\n', 'utf8');
  const jsText = `/* Auto-generated by scripts/generate-setup-i18n.mjs - DO NOT EDIT BY HAND */\nwindow.PP_SETUP_I18N = ${JSON.stringify(bundle)};\n`;
  fs.writeFileSync(path.join(OUT_DIR, 'i18n-73.js'), jsText, 'utf8');
  console.log(`[generate-setup-i18n] OK - ${bundle.languages.length} dil, ${bundle.keys.length} anahtar, 0 sizinti, 0 uzun cizgi, 0 emoji uretildi.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main();
}
